class Source(BaseModel):
    """
    Metadata for a unique retrieved source.
    Retains canonical URL, publication date, quality metrics, and human-friendly citation number.
    """
    source_id: str
    title: str
    url: str
    domain: str
    publication_date: str = "N/A"
    retrieved_at: str
    source_number: int = 1
    source_type: str = "general"  # official|academic|news|industry|company|general|unknown
    quality_score: float = 0.5  # 0.0–1.0 deterministic composite
    quality_tier: str = "adequate"  # excellent|good|adequate|low|poor
    freshness: str = "undated"  # current|recent|aging|stale|undated

    @property
    def citation_tag(self) -> str:
        return f"[Source {self.source_number}]"


class EvidenceChunkRef(BaseModel):
    """
    Reference to a specific evidence chunk stored in ChromaDB vector store.
    """
    chunk_id: str
    source_id: str
    text: str
    similarity_score: float = 0.0
    url: str = ""
    title: str = ""


class Claim(BaseModel):
    """
    Structured factual claim generated by the Writer Agent.
    Explicitly grounded in retrieved evidence chunks and sources.
    """
    claim_id: str
    headline: Optional[str] = None
    text: str
    supporting_source_ids: List[str] = Field(default_factory=list)
    evidence_chunk_ids: List[str] = Field(default_factory=list)
    confidence: float = 1.0  # 0.0 to 1.0
    verification_status: str = "grounded"  # "grounded", "insufficient_evidence", "unsupported"
    verification_notes: Optional[str] = None


class GroundedReport(BaseModel):
    """
    Full grounded research report with verified claim-evidence-source lineage.
    """
    topic: str
    claims: List[Claim] = Field(default_factory=list)
    sources: Dict[str, Source] = Field(default_factory=dict)
    evidence_chunks: Dict[str, EvidenceChunkRef] = Field(default_factory=dict)
    grounded_claims: List[Claim] = Field(default_factory=list)
    unsupported_claims: List[Claim] = Field(default_factory=list)
    insufficient_claims: List[Claim] = Field(default_factory=list)
    markdown_report: str = ""
    citation_trace: Dict[str, Any] = Field(default_factory=dict)
    research_objectives: List[str] = Field(default_factory=list)
    key_findings: List[Dict[str, str]] = Field(default_factory=list)
    thematic_analysis: List[Dict[str, Any]] = Field(default_factory=list)
    research_limitations: List[str] = Field(default_factory=list)


class WriterParseResult(tuple):
    """
    Subclasses tuple (summary, claims, conclusion) for 100% backward compatibility
    with callers unpacking `summary, claims, conclusion = parse_writer_claims_response(...)`,
    while carrying rich publication-grade report components.
    """
    def __new__(
        cls,
        summary: str,
        claims: List[Claim],
        conclusion: str,
        objectives: Optional[List[str]] = None,
        key_findings: Optional[List[Dict[str, str]]] = None,
        thematic_analysis: Optional[List[Dict[str, Any]]] = None,
        limitations: Optional[List[str]] = None,
        background_context: Optional[str] = None,
        comparative_data: Optional[List[Dict[str, Any]]] = None,
        challenges: Optional[str] = None,
    ):
        instance = super(WriterParseResult, cls).__new__(cls, (summary, claims, conclusion))
        instance.summary = summary
        instance.claims = claims
        instance.conclusion = conclusion
        instance.objectives = objectives or []
        instance.key_findings = key_findings or []
        instance.thematic_analysis = thematic_analysis or []
        instance.limitations = limitations or []
        instance.background_context = background_context or ""
        instance.comparative_data = comparative_data or []
        instance.challenges = challenges or ""
        return instance


