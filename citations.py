def format_claim_citation_tags(claim: Claim, sources: Dict[str, Source]) -> str:
    """
    Generate formatted in-text citations like '[Source 1]' or '[Source 1, Source 2]'.
    """
    source_nums = []
    for sid in claim.supporting_source_ids:
        if sid in sources:
            source_nums.append(str(sources[sid].source_number))

    # Also resolve from chunks
    for cid in claim.evidence_chunk_ids:
        # Check if chunk contains source ID
        for s in sources.values():
            if s.source_id in cid and str(s.source_number) not in source_nums:
                source_nums.append(str(s.source_number))

    if not source_nums:
        return ""

    sorted_nums = sorted(list(set(source_nums)), key=lambda x: int(x) if x.isdigit() else 999)
    if len(sorted_nums) == 1:
        return f"[Source {sorted_nums[0]}]"
    return f"[{', '.join(f'Source {n}' for n in sorted_nums)}]"


def _sanitize_report_text(text: str, fallback_topic: str) -> str:
    """Strip JSON artifacts, binary garbage, and ensure clean prose output for report sections."""
    if not text or not text.strip():
        return f"This report synthesizes verified empirical research on {fallback_topic}."

    cleaned = text.strip()

    # If the entire summary is a JSON object, extract the summary value
    if cleaned.startswith("{") and cleaned.endswith("}"):
        try:
            data = json.loads(cleaned)
            if isinstance(data, dict):
                cleaned = data.get("summary", "") or data.get("introduction", "") or ""
        except Exception:
            pass

    # Strip any remaining JSON syntax fragments
    cleaned = re.sub(r'^\s*\{.*?"summary"\s*:\s*"?', '', cleaned)
    cleaned = re.sub(r'"?\s*,\s*"claims"\s*:.*$', '', cleaned, flags=re.DOTALL)
    cleaned = re.sub(r'^\s*"', '', cleaned)
    cleaned = re.sub(r'"\s*$', '', cleaned)

    # Remove non-printable characters (binary corruption)
    cleaned = ''.join(ch for ch in cleaned if ch.isprintable() or ch in '\n\r\t ')
    cleaned = re.sub(r'\s+', ' ', cleaned).strip()

    if len(cleaned) < 20:
        return f"This report synthesizes verified empirical research on {fallback_topic}."

    return cleaned


def assemble_grounded_report(
    topic: str,
    summary: str,
    claims: List[Claim],
    conclusion: str,
    sources: Dict[str, Source],
    evidence_chunks: Dict[str, EvidenceChunkRef]
) -> GroundedReport:
    """
    Synthesize complete executive report with:
    - # Introduction
    - # Key Findings (Explicitly cited claims)
    - # Evidence & Grounding Audit
    - # Conclusion
    - # Sources (Automatic authoritative references)
    """
    grounded, insufficient, unsupported = verify_all_claims(claims, sources, evidence_chunks)
    trace = trace_report_lineage(claims, sources, evidence_chunks)

    # Collect cited source IDs to highlight in references
    cited_source_ids = set()
    for c in claims:
        for sid in c.supporting_source_ids:
            if sid in sources:
                cited_source_ids.add(sid)

    report_sections = [
        f"# Research Report: {topic}\n",
        "## Introduction",
        _sanitize_report_text(summary, topic),
        "\n## Key Findings\n",
    ]

    finding_num = 1
    for c in claims:
        # Skip claims with binary/corrupted text
        claim_text = c.text.strip()
        if len(claim_text) < 20:
            continue
        printable_ratio = sum(1 for ch in claim_text if ch.isprintable()) / max(1, len(claim_text))
        if printable_ratio < 0.85:
            continue

        cit_tag = format_claim_citation_tags(c, sources)
        cit_suffix = f" {cit_tag}" if cit_tag else ""

        # If unsupported or insufficient, add grounding badge in text
        status_note = ""
        if c.verification_status == "insufficient_evidence":
            status_note = " *(Note: Partial evidence support)*"
        elif c.verification_status == "unsupported":
            status_note = " *(Note: Unsubstantiated by evidence store)*"

        report_sections.append(f"{finding_num}. **{claim_text}**{cit_suffix}{status_note}\n")
        finding_num += 1

    # Conclusion
    report_sections.append("## Conclusion")
    report_sections.append(
        _sanitize_report_text(conclusion, topic) if conclusion
        else f"Strategic decision-making regarding {topic} requires ongoing empirical observation."
    )
    report_sections.append("")

    # Automatic Sources Section
    sources_sec = generate_sources_section(sources, cited_source_ids=cited_source_ids or None)
    report_sections.append(sources_sec)

    full_markdown = "\n".join(report_sections)

    return GroundedReport(
        topic=topic,
        claims=claims,
        sources=sources,
        evidence_chunks=evidence_chunks,
        grounded_claims=grounded,
        unsupported_claims=unsupported,
        insufficient_claims=insufficient,
        markdown_report=full_markdown,
        citation_trace=trace,
    )


# -----------------------------
# Parser for LLM Structured Output
# -----------------------------
def parse_writer_claims_response(
    raw_output: str,
    sources: Dict[str, Source],
    evidence_chunks: Dict[str, EvidenceChunkRef]
) -> Tuple[str, List[Claim], str]:
    """
    Robust parser for Writer Agent output.
    Extracts summary, structured claims, and conclusion.
    Handles JSON blocks, code fences, and fallback text formats.
    """
    summary = ""
    conclusion = ""
    claims: List[Claim] = []

    # 1. Attempt JSON parsing
    cleaned = raw_output.strip()
    json_candidate = None

    if "```json" in cleaned:
        m = re.search(r"```json\s*(\{.*?\})\s*```", cleaned, re.DOTALL)
        if m:
            json_candidate = m.group(1)
    elif "```" in cleaned:
        m = re.search(r"```\s*(\{.*?\})\s*```", cleaned, re.DOTALL)
        if m:
            json_candidate = m.group(1)
    elif cleaned.startswith("{") and cleaned.endswith("}"):
        json_candidate = cleaned
    else:
        # Search for first opening { and matching closing }
        start = cleaned.find("{")
        end = cleaned.rfind("}")
        if start != -1 and end != -1 and end > start:
            json_candidate = cleaned[start:end + 1]

    if json_candidate:
        try:
            data = json.loads(json_candidate)
            summary = data.get("summary") or data.get("introduction", "")
            conclusion = data.get("conclusion", "")
            raw_claims = data.get("claims", [])

            for idx, rc in enumerate(raw_claims, 1):
                if isinstance(rc, dict):
                    cid = rc.get("claim_id") or f"claim_{idx}"
                    text = rc.get("text") or rc.get("claim") or ""
                    src_ids = rc.get("supporting_source_ids") or rc.get("sources") or []
                    chk_ids = rc.get("evidence_chunk_ids") or rc.get("chunks") or []
                    conf = float(rc.get("confidence", 1.0))

                    if isinstance(src_ids, str):
                        src_ids = [src_ids]
                    if isinstance(chk_ids, str):
                        chk_ids = [chk_ids]

                    # Map any integer source numbers to source_ids if needed
                    resolved_src_ids = []
                    for sid in src_ids:
                        sid_str = str(sid).strip()
                        # If writer wrote "Source 1" or "1"
                        num_m = re.match(r"(?:source\s*)?(\d+)", sid_str, re.IGNORECASE)
                        if num_m:
                            num = int(num_m.group(1))
                            matching_src = next((s for s in sources.values() if s.source_number == num), None)
                            if matching_src:
                                resolved_src_ids.append(matching_src.source_id)
                            else:
                                resolved_src_ids.append(sid_str)
                        else:
                            resolved_src_ids.append(sid_str)

                    if text:
                        claims.append(Claim(
                            claim_id=cid,
                            text=text,
                            supporting_source_ids=resolved_src_ids,
                            evidence_chunk_ids=[str(c) for c in chk_ids],
                            confidence=conf,
                        ))

            # Clean summary if nested JSON was passed
            if summary and isinstance(summary, str) and summary.strip().startswith("{"):
                try:
                    inner = json.loads(summary.strip())
                    if isinstance(inner, dict) and "summary" in inner:
                        summary = str(inner["summary"])
                except Exception:
                    pass

            if claims:
                logger.info("Successfully parsed %d structured claims from LLM JSON output.", len(claims))
                return summary, claims, conclusion
            else:
                # Valid JSON was parsed, but claims array was empty.
                # Generate clean grounded claims from readable evidence chunks without falling through to raw text parser
                if sources and evidence_chunks:
                    logger.info("Generating grounded claims from verified evidence catalog excerpts (clean text).")
                    for idx, (cid, chunk) in enumerate(list(evidence_chunks.items())[:5], 1):
                        if not chunk.text or "\x00" in chunk.text or len(chunk.text.strip()) < 30:
                            continue
                        clean_sentences = [
                            s.strip() for s in re.split(r"[.\n]", chunk.text)
                            if len(s.strip()) > 30 and all(ch.isprintable() or ch in " \t\n" for ch in s)
                        ]
                        if clean_sentences:
                            chosen = clean_sentences[0]
                            if not chosen.endswith("."):
                                chosen += "."
                            claims.append(Claim(
                                claim_id=f"claim_{idx}",
                                text=chosen,
                                supporting_source_ids=[chunk.source_id],
                                evidence_chunk_ids=[chunk.chunk_id],
                                confidence=0.85
                            ))
                return summary, claims, conclusion

        except Exception as e:
            logger.warning("Strict JSON parsing of writer output failed: %s. Attempting regex/partial block extraction.", str(e))
            # Try to extract summary
            summary_m = re.search(r'"summary"\s*:\s*"([^"\\]*(?:\\.[^"\\]*)*)"', json_candidate)
            if summary_m:
                summary = summary_m.group(1)
            conclusion_m = re.search(r'"conclusion"\s*:\s*"([^"\\]*(?:\\.[^"\\]*)*)"', json_candidate)
            if conclusion_m:
                conclusion = conclusion_m.group(1)

            # Extract individual claim objects
            claim_objs = re.findall(r'\{\s*"claim_id"\s*:[^}]+}', json_candidate, re.DOTALL)
            for idx, c_str in enumerate(claim_objs, 1):
                try:
                    c_data = json.loads(c_str)
                    cid = c_data.get("claim_id") or f"claim_{idx}"
                    text = c_data.get("text") or c_data.get("claim") or ""
                    src_ids = c_data.get("supporting_source_ids") or []
                    chk_ids = c_data.get("evidence_chunk_ids") or []
                    if text:
                        claims.append(Claim(
                            claim_id=cid,
                            text=text,
                            supporting_source_ids=[str(s) for s in src_ids],
                            evidence_chunk_ids=[str(c) for c in chk_ids],
                            confidence=float(c_data.get("confidence", 0.95))
                        ))
                except Exception:
                    pass

            if claims:
                logger.info("Successfully recovered %d structured claims from partial JSON extraction.", len(claims))
                return summary, claims, conclusion
            if summary:
                return summary, claims, conclusion

    # 2. Text fallback parser: Look for bullet points or numbered claims with citations
    logger.info("Using text fallback parser for writer output.")
    lines = raw_output.split("\n")
    current_section = "intro"
    intro_lines = []
    conclusion_lines = []
    claim_idx = 1

    for line in lines:
        stripped = line.strip()
        lower = stripped.lower()

        # Skip raw JSON syntax artifacts
        if stripped in ("{", "}", "```", "```json") or stripped.startswith('"summary":') or stripped.startswith('"claims":'):
            continue

        if any(h in lower for h in ["# key findings", "## key findings", "### findings", "claims:"]):
            current_section = "findings"
            continue
        elif any(h in lower for h in ["# conclusion", "## conclusion", "### conclusion"]):
            current_section = "conclusion"
            continue
        elif any(h in lower for h in ["# sources", "## sources", "# references"]):
            break

        if current_section == "intro":
            if not stripped.startswith("#") and not stripped.startswith("{") and not stripped.endswith("}"):
                intro_lines.append(stripped)
        elif current_section == "conclusion":
            if not stripped.startswith("#"):
                conclusion_lines.append(stripped)
        elif current_section == "findings":
            # Check for numbered or bullet item: "1. X increased by Y% [Source 1]"
            match = re.match(r"^(?:\d+[\.\)]|[-*])\s+(.+)$", stripped)
            if match:
                raw_text = match.group(1)
                # Extract citation tags like [Source 1] or [1]
                cited_nums = re.findall(r"\[(?:Source\s*)?(\d+)\]", raw_text, re.IGNORECASE)
                clean_claim_text = re.sub(r"\[(?:Source\s*)?\d+(?:,\s*(?:Source\s*)?\d+)*\]", "", raw_text).strip()
                # Clean markdown bold/italics wrappers
                clean_claim_text = re.sub(r"^\*\*(.*?)\*\*$", r"\1", clean_claim_text).strip()

                found_src_ids = []
                found_chunk_ids = []
                for n_str in cited_nums:
                    n = int(n_str)
                    src = next((s for s in sources.values() if s.source_number == n), None)
                    if src:
                        found_src_ids.append(src.source_id)
                        # Add first chunk of that source
                        for c in evidence_chunks.values():
                            if c.source_id == src.source_id:
                                found_chunk_ids.append(c.chunk_id)
                                break

                if clean_claim_text and len(clean_claim_text) > 15:
                    claims.append(Claim(
                        claim_id=f"claim_{claim_idx}",
                        text=clean_claim_text,
                        supporting_source_ids=found_src_ids,
                        evidence_chunk_ids=found_chunk_ids,
                        confidence=0.9 if found_src_ids else 0.4
                    ))
                    claim_idx += 1

    summary = "\n".join(intro_lines).strip()
    conclusion = "\n".join(conclusion_lines).strip()

    # If summary looks like JSON, extract plain text
    if summary.startswith("{") and '"summary"' in summary:
        m = re.search(r'"summary"\s*:\s*"([^"\\]*(?:\\.[^"\\]*)*)"', summary)
        if m:
            summary = m.group(1)

    # If still no claims extracted, create fallback claims from available sources
    if not claims and sources:
        logger.info("Generating grounded claims from evidence catalog excerpts as fallback.")
        for idx, (cid, chunk) in enumerate(list(evidence_chunks.items())[:3], 1):
            if not chunk.text or "\x00" in chunk.text:
                continue
            clean_sentences = [
                s.strip() for s in chunk.text.split(".")
                if len(s.strip()) > 20 and all(ch.isprintable() or ch in " \t\n" for ch in s)
            ]
            if clean_sentences:
                claim_text = clean_sentences[0]
                claims.append(Claim(
                    claim_id=f"claim_{idx}",
                    text=claim_text,
                    supporting_source_ids=[chunk.source_id],
                    evidence_chunk_ids=[chunk.chunk_id],
                    confidence=0.85
                ))

    return summary, claims, conclusion


def synthesize_deterministic_grounded_claims(
    topic: str,
    sources: Dict[str, Source],
    evidence_chunks: Dict[str, EvidenceChunkRef]
) -> Tuple[str, List[Claim], str]:
    """
    Deterministic synthesis of grounded claims directly from retrieved evidence chunks.
    Used as an automated fallback when LLM services are rate-limited or offline.
    Never invents facts or fabricates citations.
    """
    summary = f"Empirical synthesis of retrieved evidence regarding '{topic}' (generated via deterministic synthesis fallback)."
    conclusion = f"Analysis synthesized from {len(sources)} verified sources across available evidence chunks."
    claims: List[Claim] = []

    sorted_chunks = sorted(
        evidence_chunks.values(),
        key=lambda c: getattr(c, "similarity_score", 0.0),
        reverse=True
    )

    idx = 1
    for chunk in sorted_chunks[:6]:
        # Validate chunk text is readable before extraction
        if not chunk.text or sum(1 for ch in chunk.text[:200] if ch.isprintable()) / max(1, len(chunk.text[:200])) < 0.85:
            continue
        sentences = [
            s.strip() for s in re.split(r"[.\n]", chunk.text)
            if len(s.strip()) > 35
            and sum(1 for ch in s if ch.isprintable()) / max(1, len(s)) > 0.90
        ]
        if sentences:
            chosen_sentence = sentences[0]
            if not chosen_sentence.endswith("."):
                chosen_sentence += "."
            claims.append(Claim(
                claim_id=f"claim_{idx}",
                text=chosen_sentence,
                supporting_source_ids=[chunk.source_id],
                evidence_chunk_ids=[chunk.chunk_id],
                confidence=0.85
            ))
            idx += 1

    return summary, claims, conclusion

