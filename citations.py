# Claim Verification & Grounding Engine
# -----------------------------
def verify_claim(
    claim: Claim,
    sources: Dict[str, Source],
    evidence_chunks: Dict[str, EvidenceChunkRef]
) -> Claim:
    """
    Verify claim grounding against the evidence store:
    1. Rejects invented / hallucinated sources and chunk IDs.
    2. Validates that referenced chunks belong to the referenced sources.
    3. Checks text overlap and semantic grounding.
    4. Sets status to 'grounded', 'insufficient_evidence', or 'unsupported'.
    """
    # 1. Check for invented / non-existent sources
    valid_source_ids = [sid for sid in claim.supporting_source_ids if sid in sources]
    invalid_source_ids = [sid for sid in claim.supporting_source_ids if sid not in sources]

    # Also resolve any source referenced by chunk if source_id was omitted
    valid_chunk_ids = [cid for cid in claim.evidence_chunk_ids if cid in evidence_chunks]
    invalid_chunk_ids = [cid for cid in claim.evidence_chunk_ids if cid not in evidence_chunks]

    for cid in valid_chunk_ids:
        chunk_obj = evidence_chunks[cid]
        if chunk_obj.source_id in sources and chunk_obj.source_id not in valid_source_ids:
            valid_source_ids.append(chunk_obj.source_id)

    # If all sources were invented or no sources provided
    if not valid_source_ids and not valid_chunk_ids:
        claim.verification_status = "unsupported"
        if invalid_source_ids or invalid_chunk_ids:
            claim.verification_notes = (
                f"Invented citation detected. Cited sources {invalid_source_ids} and "
                f"chunks {invalid_chunk_ids} do not exist in the evidence store."
            )
        else:
            claim.verification_notes = "No supporting evidence or source provided."
        claim.confidence = min(claim.confidence, 0.2)
        return claim

    # If some cited sources were invented
    if invalid_source_ids or invalid_chunk_ids:
        logger.warning(
            "Claim '%s' cited invalid sources %s or chunks %s. Filtering to verified evidence.",
            claim.claim_id, invalid_source_ids, invalid_chunk_ids
        )
        claim.supporting_source_ids = valid_source_ids
        claim.evidence_chunk_ids = valid_chunk_ids

    # 2. Check grounding evidence text
    supporting_texts = []
    for cid in valid_chunk_ids:
        supporting_texts.append(evidence_chunks[cid].text)

    # If chunks not explicitly given, collect texts from valid sources
    if not supporting_texts:
        for sid in valid_source_ids:
            for c in evidence_chunks.values():
                if c.source_id == sid:
                    supporting_texts.append(c.text)

    combined_evidence = " ".join(supporting_texts).lower()

    if not combined_evidence:
        claim.verification_status = "insufficient_evidence"
        claim.verification_notes = "Referenced source has empty evidence text in the store."
        claim.confidence = min(claim.confidence, 0.4)
        return claim

    # Heuristic textual grounding check: significant words in claim must appear in evidence
    claim_words = re.findall(r"\b[a-zA-Z0-9_-]{3,}\b", claim.text.lower())
    stop_words = {
        "the", "and", "for", "with", "that", "this", "from", "are", "was", "were",
        "has", "have", "had", "will", "can", "could", "should", "would", "about",
        "into", "over", "such", "than", "then", "more", "most", "been", "also"
    }
    significant_words = [w for w in claim_words if w not in stop_words]

    if not significant_words:
        claim.verification_status = "grounded"
        return claim

    overlap_count = sum(1 for w in significant_words if w in combined_evidence)
    overlap_ratio = overlap_count / len(significant_words)

    # Numeric/quantitative factual check: if numbers are in the claim, check if they exist in evidence
    claim_numbers = re.findall(r"\b\d+(?:\.\d+)?%?\b", claim.text)
    number_match = True
    if claim_numbers:
        number_match = any(num.lower() in combined_evidence for num in claim_numbers)

    if overlap_ratio >= 0.35 and number_match:
        claim.verification_status = "grounded"
        claim.verification_notes = f"Verified: {overlap_count}/{len(significant_words)} key terms and metrics grounded in evidence."
    elif overlap_ratio >= 0.20:
        claim.verification_status = "insufficient_evidence"
        claim.verification_notes = (
            f"Insufficient evidence: only {overlap_count}/{len(significant_words)} terms matched in cited excerpts. "
            "Claim may contain unverified extrapolations."
        )
        claim.confidence = min(claim.confidence, 0.5)
    else:
        claim.verification_status = "unsupported"
        claim.verification_notes = (
            f"Unsupported: Low grounding overlap ({overlap_count}/{len(significant_words)} terms). "
            "Evidence does not substantiate this claim."
        )
        claim.confidence = min(claim.confidence, 0.3)

    return claim


def verify_all_claims(
    claims: List[Claim],
    sources: Dict[str, Source],
    evidence_chunks: Dict[str, EvidenceChunkRef]
) -> Tuple[List[Claim], List[Claim], List[Claim]]:
    """
    Verify all claims and partition into (grounded, insufficient, unsupported).
    """
    grounded: List[Claim] = []
    insufficient: List[Claim] = []
    unsupported: List[Claim] = []

    for c in claims:
        verified_c = verify_claim(c, sources, evidence_chunks)
        if verified_c.verification_status == "grounded":
            grounded.append(verified_c)
        elif verified_c.verification_status == "insufficient_evidence":
            insufficient.append(verified_c)
        else:
            unsupported.append(verified_c)

    return grounded, insufficient, unsupported


