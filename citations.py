"""
SYNAPSE AI - Evidence Grounding & Citation Integrity Engine.
Implements:
Claim
 ↓
Evidence
 ↓
Source
 ↓
Citation

Guarantees:
- Every factual claim references supporting evidence.
- No citations can be invented (hallucinated sources are detected and rejected).
- Citations originate strictly from retrieved evidence chunks.
- Every source retains its original canonical URL.
- Support for multiple sources per claim.
- Detection of unsupported claims and claims with insufficient evidence.
- Automatic generation of the Sources section.
- End-to-end tracing: Report → Claim → Evidence → Source → URL.
"""

import json
import logging
import re
from typing import Any, Dict, List, Optional, Set, Tuple
from pydantic import BaseModel, Field

