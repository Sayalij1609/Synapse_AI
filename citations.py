# Registry Builders
# -----------------------------
def build_source_registry(
    retrieved_evidence: List[Any]
) -> Tuple[Dict[str, Source], Dict[str, EvidenceChunkRef]]:
    """
    Index unique sources and evidence chunks from retrieved vector store records.
    Assigns stable human-friendly source numbers (1, 2, 3...).
    """
    sources: Dict[str, Source] = {}
    evidence_chunks: Dict[str, EvidenceChunkRef] = {}
    url_to_source_id: Dict[str, str] = {}
    source_counter = 1

    for ev in retrieved_evidence:
        # Support both RetrievedEvidence object and dict
        if hasattr(ev, "model_dump"):
            data = ev.model_dump()
        elif isinstance(ev, dict):
            data = ev
        else:
            continue

        sid = data.get("source_id") or ""
        url = data.get("url") or ""
        cid = data.get("chunk_id") or ""
        text = data.get("text") or ""
        title = data.get("title") or "Web Document"
        domain = data.get("domain") or "web"
        pub_date = data.get("publication_date") or "N/A"
        retrieved_at = data.get("retrieval_timestamp") or data.get("retrieved_at") or "N/A"
        similarity = float(data.get("similarity_score", 0.0))

        if not sid and url:
            import hashlib
            sid = hashlib.sha256(url.lower().encode("utf-8")).hexdigest()[:16]

        if not sid:
            continue

        # Register Source if not already present
        if sid not in sources:
            sources[sid] = Source(
                source_id=sid,
                title=title,
                url=url,
                domain=domain,
                publication_date=pub_date,
                retrieved_at=retrieved_at,
                source_number=source_counter,
            )
            url_to_source_id[url.lower()] = sid
            source_counter += 1

        # Register Evidence Chunk
        if cid:
            evidence_chunks[cid] = EvidenceChunkRef(
                chunk_id=cid,
                source_id=sid,
                text=text,
                similarity_score=similarity,
                url=url,
                title=title,
            )

    return sources, evidence_chunks


def format_evidence_catalog_for_writer(
    sources: Dict[str, Source],
    evidence_chunks: Dict[str, EvidenceChunkRef]
) -> str:
    """
    Format a structured, unambiguous evidence catalog for the Writer LLM.
    Explicitly labels valid Source IDs, Source Numbers, and Chunk IDs.
    """
    if not sources:
        return "No verified sources available in evidence store."

    lines = [
        "============================================================",
        "AUTHORITATIVE EVIDENCE CATALOG (ONLY CITE THESE VALID SOURCES)",
        "============================================================",
    ]

    for sid, src in sources.items():
        lines.append(f"\n[Source {src.source_number}] (source_id: '{sid}')")
        lines.append(f"Title: {src.title}")
        lines.append(f"URL: {src.url} | Domain: {src.domain} | Published: {src.publication_date}")
        lines.append("Supporting Evidence Chunks:")

        src_chunks = [c for c in evidence_chunks.values() if c.source_id == sid]
        if not src_chunks:
            lines.append("  (No specific chunk excerpts)")
        for chunk in src_chunks:
            lines.append(f"  - Chunk ID: '{chunk.chunk_id}' (Relevance: {chunk.similarity_score})")
            clean_excerpt = chunk.text.replace("\n", " ").strip()
            lines.append(f"    Excerpt: \"{clean_excerpt}\"")

    lines.append("\n============================================================")
    return "\n".join(lines)


# -----------------------------
# Claim Verification & Grounding Engine
# -----------------------------
def verify_claim(
    claim: Claim,
    sources: Dict[str, Source],
    evidence_chunks: Dict[str, EvidenceChunkRef]
) -> Claim:
    """
    Verify claim grounding against the evidence store:
    1. Rejects invented / hallucinated sources and chunk IDs.
    2. Validates that referenced chunks belong to the referenced sources.
    3. Checks text overlap and semantic grounding.
    4. Sets status to 'grounded', 'insufficient_evidence', or 'unsupported'.
    """
    # 1. Check for invented / non-existent sources
    valid_source_ids = [sid for sid in claim.supporting_source_ids if sid in sources]
    invalid_source_ids = [sid for sid in claim.supporting_source_ids if sid not in sources]

    # Also resolve any source referenced by chunk if source_id was omitted
    valid_chunk_ids = [cid for cid in claim.evidence_chunk_ids if cid in evidence_chunks]
    invalid_chunk_ids = [cid for cid in claim.evidence_chunk_ids if cid not in evidence_chunks]

    for cid in valid_chunk_ids:
        chunk_obj = evidence_chunks[cid]
        if chunk_obj.source_id in sources and chunk_obj.source_id not in valid_source_ids:
            valid_source_ids.append(chunk_obj.source_id)

    # If all sources were invented or no sources provided
    if not valid_source_ids and not valid_chunk_ids:
        claim.verification_status = "unsupported"
        if invalid_source_ids or invalid_chunk_ids:
            claim.verification_notes = (
                f"Invented citation detected. Cited sources {invalid_source_ids} and "
                f"chunks {invalid_chunk_ids} do not exist in the evidence store."
            )
        else:
            claim.verification_notes = "No supporting evidence or source provided."
        claim.confidence = min(claim.confidence, 0.2)
        return claim

    # If some cited sources were invented
    if invalid_source_ids or invalid_chunk_ids:
        logger.warning(
            "Claim '%s' cited invalid sources %s or chunks %s. Filtering to verified evidence.",
            claim.claim_id, invalid_source_ids, invalid_chunk_ids
        )
        claim.supporting_source_ids = valid_source_ids
        claim.evidence_chunk_ids = valid_chunk_ids

    # 2. Check grounding evidence text
    supporting_texts = []
    for cid in valid_chunk_ids:
        supporting_texts.append(evidence_chunks[cid].text)

    # If chunks not explicitly given, collect texts from valid sources
    if not supporting_texts:
        for sid in valid_source_ids:
            for c in evidence_chunks.values():
                if c.source_id == sid:
                    supporting_texts.append(c.text)

    combined_evidence = " ".join(supporting_texts).lower()

    if not combined_evidence:
        claim.verification_status = "insufficient_evidence"
        claim.verification_notes = "Referenced source has empty evidence text in the store."
        claim.confidence = min(claim.confidence, 0.4)
        return claim

    # Heuristic textual grounding check: significant words in claim must appear in evidence
    claim_words = re.findall(r"\b[a-zA-Z0-9_-]{3,}\b", claim.text.lower())
    stop_words = {
        "the", "and", "for", "with", "that", "this", "from", "are", "was", "were",
        "has", "have", "had", "will", "can", "could", "should", "would", "about",
        "into", "over", "such", "than", "then", "more", "most", "been", "also"
    }
    significant_words = [w for w in claim_words if w not in stop_words]

    if not significant_words:
        claim.verification_status = "grounded"
        return claim

    overlap_count = sum(1 for w in significant_words if w in combined_evidence)
    overlap_ratio = overlap_count / len(significant_words)

    # Numeric/quantitative factual check: if numbers are in the claim, check if they exist in evidence
    claim_numbers = re.findall(r"\b\d+(?:\.\d+)?%?\b", claim.text)
    number_match = True
    if claim_numbers:
        number_match = any(num.lower() in combined_evidence for num in claim_numbers)

    if overlap_ratio >= 0.35 and number_match:
        claim.verification_status = "grounded"
        claim.verification_notes = f"Verified: {overlap_count}/{len(significant_words)} key terms and metrics grounded in evidence."
    elif overlap_ratio >= 0.20:
        claim.verification_status = "insufficient_evidence"
        claim.verification_notes = (
            f"Insufficient evidence: only {overlap_count}/{len(significant_words)} terms matched in cited excerpts. "
            "Claim may contain unverified extrapolations."
        )
        claim.confidence = min(claim.confidence, 0.5)
    else:
        claim.verification_status = "unsupported"
        claim.verification_notes = (
            f"Unsupported: Low grounding overlap ({overlap_count}/{len(significant_words)} terms). "
            "Evidence does not substantiate this claim."
        )
        claim.confidence = min(claim.confidence, 0.3)

    return claim


def verify_all_claims(
    claims: List[Claim],
    sources: Dict[str, Source],
    evidence_chunks: Dict[str, EvidenceChunkRef]
) -> Tuple[List[Claim], List[Claim], List[Claim]]:
    """
    Verify all claims and partition into (grounded, insufficient, unsupported).
    """
    grounded: List[Claim] = []
    insufficient: List[Claim] = []
    unsupported: List[Claim] = []

    for c in claims:
        verified_c = verify_claim(c, sources, evidence_chunks)
        if verified_c.verification_status == "grounded":
            grounded.append(verified_c)
        elif verified_c.verification_status == "insufficient_evidence":
            insufficient.append(verified_c)
        else:
            unsupported.append(verified_c)

    return grounded, insufficient, unsupported


# -----------------------------
# Lineage Tracing: Report → Claim → Evidence → Source → URL
# -----------------------------
def trace_claim_lineage(
    claim: Claim,
    sources: Dict[str, Source],
    evidence_chunks: Dict[str, EvidenceChunkRef]
) -> Dict[str, Any]:
    """
    Trace the complete provenance chain for a single claim:
    Claim → Evidence Chunks → Sources → Canonical URLs.
    """
    evidence_chain = []

    # Collect all chunks cited or belonging to cited sources
    relevant_chunks = []
    for cid in claim.evidence_chunk_ids:
        if cid in evidence_chunks:
            relevant_chunks.append(evidence_chunks[cid])

    if not relevant_chunks:
        for sid in claim.supporting_source_ids:
            for c in evidence_chunks.values():
                if c.source_id == sid:
                    relevant_chunks.append(c)

    for ch in relevant_chunks:
        src = sources.get(ch.source_id)
        evidence_chain.append({
            "chunk_id": ch.chunk_id,
            "excerpt": ch.text[:250],
            "similarity_score": ch.similarity_score,
            "source": {
                "source_id": src.source_id if src else ch.source_id,
                "title": src.title if src else ch.title,
                "url": src.url if src else ch.url,
                "domain": src.domain if src else "web",
                "publication_date": src.publication_date if src else "N/A",
                "retrieved_at": src.retrieved_at if src else "N/A",
                "source_number": src.source_number if src else 0,
                "citation_tag": src.citation_tag if src else "[Source]",
            }
        })

    # Also list any source without explicit chunk
    for sid in claim.supporting_source_ids:
        if not any(ec["source"]["source_id"] == sid for ec in evidence_chain):
            src = sources.get(sid)
            if src:
                evidence_chain.append({
                    "chunk_id": "document_level",
                    "excerpt": "(Full source referenced)",
                    "similarity_score": 1.0,
                    "source": {
                        "source_id": src.source_id,
                        "title": src.title,
                        "url": src.url,
                        "domain": src.domain,
                        "publication_date": src.publication_date,
                        "retrieved_at": src.retrieved_at,
                        "source_number": src.source_number,
                        "citation_tag": src.citation_tag,
                    }
                })

    return {
        "claim_id": claim.claim_id,
        "claim_text": claim.text,
        "confidence": claim.confidence,
        "verification_status": claim.verification_status,
        "verification_notes": claim.verification_notes,
        "evidence_chain": evidence_chain,
    }


def trace_report_lineage(
    claims: List[Claim],
    sources: Dict[str, Source],
    evidence_chunks: Dict[str, EvidenceChunkRef]
) -> Dict[str, Any]:
    """
    Produce comprehensive audit trace for the entire report.
    """
    traces = [trace_claim_lineage(c, sources, evidence_chunks) for c in claims]
    grounded_count = sum(1 for c in claims if c.verification_status == "grounded")
    insufficient_count = sum(1 for c in claims if c.verification_status == "insufficient_evidence")
    unsupported_count = sum(1 for c in claims if c.verification_status == "unsupported")

    return {
        "total_claims": len(claims),
        "grounded_claims": grounded_count,
        "insufficient_claims": insufficient_count,
        "unsupported_claims": unsupported_count,
        "grounding_ratio": round(grounded_count / max(1, len(claims)), 3),
        "claims_trace": traces,
    }


# -----------------------------
# Automated Sources Section Generator
# -----------------------------
def generate_sources_section(
    sources: Dict[str, Source],
    cited_source_ids: Optional[Set[str]] = None
) -> str:
    """
    Generate an authoritative '# Sources' section automatically.
    Preserves original canonical URLs, publication dates, and domains.
    """
    if not sources:
        return "# Sources\n\nNo verified external sources were cited."

    # If specific cited sources provided, filter; otherwise list all active sources
    target_sources = (
        [s for s in sources.values() if s.source_id in cited_source_ids]
        if cited_source_ids
        else list(sources.values())
    )

    if not target_sources:
        target_sources = list(sources.values())

    # Sort by source_number
    target_sources.sort(key=lambda s: s.source_number)

    lines = ["# Sources\n"]
    for s in target_sources:
        pub_str = f" | Published: {s.publication_date}" if s.publication_date and s.publication_date != "N/A" else ""
        lines.append(
            f"- **[{s.source_number}]** [{s.title}]({s.url}) — *{s.domain}*{pub_str}"
        )

    return "\n".join(lines)


